const root = document.documentElement;
const themeButton = document.querySelector('.theme-toggle');
try {
  if (localStorage.getItem('yk-theme') === 'dark') root.dataset.theme = 'dark';
} catch { /* Storage is optional. */ }
themeButton?.setAttribute('aria-pressed', String(root.dataset.theme === 'dark'));
themeButton?.addEventListener('click', () => {
  const dark = root.dataset.theme !== 'dark';
  root.dataset.theme = dark ? 'dark' : 'light';
  themeButton.setAttribute('aria-pressed', String(dark));
  try { localStorage.setItem('yk-theme', dark ? 'dark' : 'light'); } catch {}
});

document.querySelectorAll('[data-filter]').forEach(button => {
  button.addEventListener('click', () => {
    const filter = button.dataset.filter;
    document.querySelectorAll('[data-filter]').forEach(b => b.setAttribute('aria-pressed', String(b === button)));
    let visible = 0;
    document.querySelectorAll('[data-category]').forEach(card => {
      card.hidden = filter !== 'all' && card.dataset.category !== filter;
      if (!card.hidden) visible++;
    });
    document.querySelector('#filter-status').textContent = document.documentElement.lang === 'ko' ? `${visible}개 프로젝트 표시` : `${visible} projects shown`;
  });
});

document.querySelector('[data-copy]')?.addEventListener('click', async event => {
  const button = event.currentTarget;
  try {
    await navigator.clipboard.writeText(button.dataset.copy);
    button.textContent = button.dataset.success;
  } catch {
    button.textContent = button.dataset.error;
  }
  setTimeout(() => { button.textContent = button.dataset.label; }, 4000);
});

if ('IntersectionObserver' in window) {
  const observer = new IntersectionObserver(entries => {
    entries.forEach(entry => {
      if (entry.isIntersecting) document.querySelectorAll('.nav-links a').forEach(a => {
        if (a.hash === `#${entry.target.id}`) a.setAttribute('aria-current', 'location');
        else a.removeAttribute('aria-current');
      });
    });
  }, { rootMargin: '-10% 0px -60% 0px' });
  document.querySelectorAll('main section[id]').forEach(section => observer.observe(section));
}

// The feed is generated by GitHub Pages from _posts on every publication.
const latestNotes = document.querySelector('[data-latest-notes]');
if (latestNotes) {
  fetch('/notes/feed.json', { cache: 'no-cache' })
    .then(response => { if (!response.ok) throw new Error('Notes unavailable'); return response.json(); })
    .then(posts => {
      if (!Array.isArray(posts)) throw new Error('Invalid notes feed');
      const fragment = document.createDocumentFragment();
      const en = root.lang === 'en';
      for (const post of posts.slice(0, 3)) {
        if (typeof post.title !== 'string' || typeof post.url !== 'string') continue;
        const url = new URL(post.url, location.origin);
        if (url.origin !== location.origin || !url.pathname.startsWith('/notes/')) continue;
        const row = document.createElement('article'); row.className = 'note-row';
        const date = document.createElement('span'); date.className = 'note-index'; date.textContent = String(post.date || '');
        const copy = document.createElement('div');
        const category = document.createElement('span'); category.className = 'eyebrow';
        category.textContent = `${post.category || 'NOTES'} / ${post.lang === 'en' ? 'EN' : 'KO'}`;
        const heading = document.createElement('h3');
        const link = document.createElement('a'); link.href = url.pathname; link.textContent = post.title; heading.append(link);
        const summary = document.createElement('p'); summary.textContent = String(post.summary || '');
        copy.append(category, heading, summary);
        const read = document.createElement('a'); read.href = url.pathname; read.textContent = '↗'; read.setAttribute('aria-label', `${post.title} ${en ? '— read note' : '읽기'}`);
        row.append(date, copy, read); fragment.append(row);
      }
      if (fragment.childNodes.length) latestNotes.replaceChildren(fragment);
      else if (posts.length === 0) {
        const empty = document.createElement('p'); empty.className = 'notes-empty';
        empty.textContent = en ? 'The first note is on its way.' : '첫 번째 기록을 준비하고 있습니다.';
        latestNotes.replaceChildren(empty);
      }
    })
    .catch(() => { /* The server-rendered all-notes link remains usable. */ });
}
